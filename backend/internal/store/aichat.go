package store

import (
	"context"
	"database/sql"
	"encoding/json"
)

// The AI consultation's conversation, kept on the server: a question is saved the moment it is
// asked and answered in the background, so a reload, a closed tab or another device finds the
// answer waiting instead of losing it.
const aiChatSchema = `
CREATE TABLE IF NOT EXISTS ai_turns (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL,
  brief      TEXT NOT NULL,
  opts       TEXT NOT NULL DEFAULT '{}',      -- {"buyable_only":…, "max_price":…}
  status     TEXT NOT NULL DEFAULT 'pending', -- pending | done | error
  result     TEXT,                            -- the answer, as JSON
  error      TEXT NOT NULL DEFAULT '',
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_ai_turns_user ON ai_turns(user_id, id DESC);
`

type AITurn struct {
	ID        int64           `json:"id"`
	Brief     string          `json:"brief"`
	Opts      json.RawMessage `json:"opts"`
	Status    string          `json:"status"`
	Result    json.RawMessage `json:"result,omitempty"`
	Error     string          `json:"error,omitempty"`
	CreatedAt int64           `json:"created_at"`
}

// aiTurnStale is how long a question may stay unanswered before it counts as lost (the server
// restarted while answering it).
const aiTurnStale = 5 * 60

func (s *Store) AddAITurn(ctx context.Context, userID int64, brief string, opts any) (int64, error) {
	js, _ := json.Marshal(opts)
	ts := now()
	var id int64
	err := s.DB.QueryRowContext(ctx, `INSERT INTO ai_turns(user_id, brief, opts, created_at, updated_at) VALUES(?,?,?,?,?) RETURNING id`,
		userID, brief, string(js), ts, ts).Scan(&id)
	return id, err
}

// FinishAITurn stores the answer (or why there is none).
func (s *Store) FinishAITurn(ctx context.Context, id int64, result any, errText string) error {
	status, res := "done", sql.NullString{}
	if errText != "" {
		status = "error"
	} else {
		js, err := json.Marshal(result)
		if err != nil {
			return err
		}
		res = sql.NullString{String: string(js), Valid: true}
	}
	_, err := s.DB.ExecContext(ctx, `UPDATE ai_turns SET status=?, result=?, error=?, updated_at=? WHERE id=?`, status, res, errText, now(), id)
	return err
}

// AITurns is one account's conversation, oldest first: the last `limit` turns.
func (s *Store) AITurns(ctx context.Context, userID int64, limit int) ([]AITurn, error) {
	s.DB.ExecContext(ctx, `UPDATE ai_turns SET status='error', error='interrupted', updated_at=? WHERE user_id=? AND status='pending' AND created_at < ?`,
		now(), userID, now()-aiTurnStale)
	rows, err := s.DB.QueryContext(ctx, `SELECT id, brief, opts, status, COALESCE(result,''), error, created_at FROM
		(SELECT * FROM ai_turns WHERE user_id=? ORDER BY id DESC LIMIT ?) t ORDER BY id`, userID, limit)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []AITurn{}
	for rows.Next() {
		var t AITurn
		var opts, res string
		if err := rows.Scan(&t.ID, &t.Brief, &opts, &t.Status, &res, &t.Error, &t.CreatedAt); err != nil {
			return nil, err
		}
		t.Opts = json.RawMessage(opts)
		if res != "" {
			t.Result = json.RawMessage(res)
		}
		out = append(out, t)
	}
	return out, rows.Err()
}

// PendingAITurns counts questions still being answered, so one account cannot pile them up.
func (s *Store) PendingAITurns(ctx context.Context, userID int64) int {
	var n int
	s.DB.QueryRowContext(ctx, `SELECT COUNT(*) FROM ai_turns WHERE user_id=? AND status='pending' AND created_at >= ?`, userID, now()-aiTurnStale).Scan(&n)
	return n
}

func (s *Store) ClearAITurns(ctx context.Context, userID int64) error {
	_, err := s.DB.ExecContext(ctx, `DELETE FROM ai_turns WHERE user_id=?`, userID)
	return err
}
