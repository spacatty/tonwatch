// Support: a ticket is one conversation between an account and the team. People write from the
// bot or the web app, the team answers from the admin panel or by replying in the bot, and every
// message lands here whichever side it came through.
const supportSchema = `
CREATE TABLE IF NOT EXISTS support_tickets (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL,
  subject    TEXT NOT NULL DEFAULT '',
  status     TEXT NOT NULL DEFAULT 'open',  -- open | closed
  last_from  TEXT NOT NULL DEFAULT 'user',  -- user | staff: who wrote last, so the team sees what waits on them
  user_seen  BIGINT NOT NULL DEFAULT 0,     -- the last message id the account has read
  staff_seen BIGINT NOT NULL DEFAULT 0,     -- the last message id the team has read
  created_at BIGINT NOT NULL,
  updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_support_tickets_user ON support_tickets(user_id, id DESC);
CREATE INDEX IF NOT EXISTS ix_support_tickets_updated ON support_tickets(status, updated_at DESC);

CREATE TABLE IF NOT EXISTS support_messages (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id  BIGINT NOT NULL REFERENCES support_tickets(id) ON DELETE CASCADE,
  author_id  BIGINT NOT NULL,               -- the account that wrote it (the customer, or the admin)
  staff      INTEGER NOT NULL DEFAULT 0,    -- 1: written by the team
  body       TEXT NOT NULL,
  via        TEXT NOT NULL DEFAULT 'web',   -- web | bot
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_support_messages_ticket ON support_messages(ticket_id, id);
`

type Ticket struct {
	ID        int64  `json:"id"`
	UserID    int64  `json:"user_id"`
	Subject   string `json:"subject"`
	Status    string `json:"status"`
	LastFrom  string `json:"last_from"`
	Unread    int    `json:"unread"` // messages from the other side not read yet (other side = the reader's)
	Preview   string `json:"preview"`
	CreatedAt int64  `json:"created_at"`
	UpdatedAt int64  `json:"updated_at"`
	User      string `json:"user,omitempty"` // admin lists: the account's label
}

type SupportMessage struct {
	ID        int64  `json:"id"`
	TicketID  int64  `json:"ticket_id"`
	AuthorID  int64  `json:"author_id"`
	Staff     bool   `json:"staff"`
	Body      string `json:"body"`
	Via       string `json:"via"`
	CreatedAt int64  `json:"created_at"`
	Author    string `json:"author,omitempty"` // the admin's label, shown to the team only
}

// ticketCols reads a ticket with its unread count for one side and its latest message.
func ticketCols(staff bool) string {
	seen, other := "t.user_seen", "1"
	if staff {
		seen, other = "t.staff_seen", "0"
	}
	return `t.id, t.user_id, t.subject, t.status, t.last_from, t.created_at, t.updated_at,
		(SELECT count(*) FROM support_messages m WHERE m.ticket_id=t.id AND m.staff=` + other + ` AND m.id > ` + seen + `),
		COALESCE((SELECT body FROM support_messages m WHERE m.ticket_id=t.id ORDER BY m.id DESC LIMIT 1), '')`
}

func scanTickets(rows *sql.Rows) ([]Ticket, error) {
	defer rows.Close()
	out := []Ticket{}
	for rows.Next() {
		var t Ticket
		if err := rows.Scan(&t.ID, &t.UserID, &t.Subject, &t.Status, &t.LastFrom, &t.CreatedAt, &t.UpdatedAt, &t.Unread, &t.Preview); err != nil {
			return nil, err
		}
		if r := []rune(t.Preview); len(r) > 140 {
			t.Preview = string(r[:140]) + "…"
		}
		out = append(out, t)
	}
	return out, rows.Err()
}

// Ticket reads one ticket, with the unread count of the given side.
func (s *Store) Ticket(ctx context.Context, id int64, staff bool) (*Ticket, error) {
	rows, err := s.DB.QueryContext(ctx, `SELECT `+ticketCols(staff)+` FROM support_tickets t WHERE t.id=?`, id)
	if err != nil {
		return nil, err
	}
	ts, err := scanTickets(rows)
	if err != nil || len(ts) == 0 {
		return nil, err
	}
	return &ts[0], nil
}

// UserTickets is one account's tickets, newest activity first.
func (s *Store) UserTickets(ctx context.Context, userID int64, limit int) ([]Ticket, error) {
	rows, err := s.DB.QueryContext(ctx, `SELECT `+ticketCols(false)+` FROM support_tickets t WHERE t.user_id=? ORDER BY t.updated_at DESC LIMIT ?`, userID, limit)
	if err != nil {
		return nil, err
	}
	return scanTickets(rows)
}

// Tickets is the team's queue. status "open" | "closed" | "" (all); open tickets waiting on the
// team come first.
func (s *Store) Tickets(ctx context.Context, status string, limit int) ([]Ticket, error) {
	where, args := "TRUE", []any{}
	if status != "" {
		where, args = "t.status=?", append(args, status)
	}
	rows, err := s.DB.QueryContext(ctx, `SELECT `+ticketCols(true)+` FROM support_tickets t WHERE `+where+`
		ORDER BY (t.status='open' AND t.last_from='user') DESC, t.updated_at DESC LIMIT ?`, append(args, limit)...)
	if err != nil {
		return nil, err
	}
	return scanTickets(rows)
}

// OpenTicket is the account's latest open ticket, or nil.
func (s *Store) OpenTicket(ctx context.Context, userID int64) (*Ticket, error) {
	var id int64
	err := s.DB.QueryRowContext(ctx, `SELECT id FROM support_tickets WHERE user_id=? AND status='open' ORDER BY id DESC LIMIT 1`, userID).Scan(&id)
	if errors.Is(err, sql.ErrNoRows) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	return s.Ticket(ctx, id, false)
}

func (s *Store) CreateTicket(ctx context.Context, userID int64, subject string) (int64, error) {
	ts := now()
	var id int64
	err := s.DB.QueryRowContext(ctx, `INSERT INTO support_tickets(user_id, subject, created_at, updated_at) VALUES(?,?,?,?) RETURNING id`,
		userID, subject, ts, ts).Scan(&id)
	return id, err
}

// AddSupportMessage appends a message, reopens the ticket and marks it read by the side that wrote.
func (s *Store) AddSupportMessage(ctx context.Context, ticketID, authorID int64, staff bool, body, via string) (SupportMessage, error) {
	m := SupportMessage{TicketID: ticketID, AuthorID: authorID, Staff: staff, Body: body, Via: via, CreatedAt: now()}
	tx, err := s.DB.BeginTx(ctx, nil)
	if err != nil {
		return m, err
	}
	defer tx.Rollback()
	if err := tx.QueryRowContext(ctx, `INSERT INTO support_messages(ticket_id, author_id, staff, body, via, created_at) VALUES(?,?,?,?,?,?) RETURNING id`,
		ticketID, authorID, b2i(staff), body, via, m.CreatedAt).Scan(&m.ID); err != nil {
		return m, err
	}
	from, seen := "user", "user_seen"
	if staff {
		from, seen = "staff", "staff_seen"
	}
	if _, err := tx.ExecContext(ctx, `UPDATE support_tickets SET status='open', last_from=?, `+seen+`=?, updated_at=? WHERE id=?`,
		from, m.ID, m.CreatedAt, ticketID); err != nil {
		return m, err
	}
	return m, tx.Commit()
}

// SupportMessages is a ticket's thread, oldest first.
func (s *Store) SupportMessages(ctx context.Context, ticketID int64) ([]SupportMessage, error) {
	rows, err := s.DB.QueryContext(ctx, `SELECT id, ticket_id, author_id, staff, body, via, created_at FROM support_messages WHERE ticket_id=? ORDER BY id`, ticketID)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []SupportMessage{}
	for rows.Next() {
		var m SupportMessage
		var staff int
		if err := rows.Scan(&m.ID, &m.TicketID, &m.AuthorID, &staff, &m.Body, &m.Via, &m.CreatedAt); err != nil {
			return nil, err
		}
		m.Staff = staff == 1
		out = append(out, m)
	}
	return out, rows.Err()
}

// MarkTicketSeen records that one side has read the thread up to its latest message.
func (s *Store) MarkTicketSeen(ctx context.Context, ticketID int64, staff bool) error {
	col := "user_seen"
	if staff {
		col = "staff_seen"
	}
	_, err := s.DB.ExecContext(ctx, `UPDATE support_tickets SET `+col+`=COALESCE((SELECT max(id) FROM support_messages WHERE ticket_id=?), 0) WHERE id=?`, ticketID, ticketID)
	return err
}

func (s *Store) SetTicketStatus(ctx context.Context, ticketID int64, status string) error {
	_, err := s.DB.ExecContext(ctx, `UPDATE support_tickets SET status=?, updated_at=? WHERE id=?`, status, now(), ticketID)
	return err
}

// SupportUnread is how many team messages the account has not read, over all its tickets.
func (s *Store) SupportUnread(ctx context.Context, userID int64) int {
	var n int
	s.DB.QueryRowContext(ctx, `SELECT count(*) FROM support_messages m JOIN support_tickets t ON t.id=m.ticket_id
		WHERE t.user_id=? AND m.staff=1 AND m.id > t.user_seen`, userID).Scan(&n)
	return n
}

// SupportWaiting is how many open tickets wait on the team.
func (s *Store) SupportWaiting(ctx context.Context) int {
	var n int
	s.DB.QueryRowContext(ctx, `SELECT count(*) FROM support_tickets WHERE status='open' AND last_from='user'`).Scan(&n)
	return n
}

// AdminTgIDs are the Telegram chats of the admins who linked Telegram: they hear about new
// support messages in the bot.
func (s *Store) AdminTgIDs(ctx context.Context) []int64 {
	rows, err := s.DB.QueryContext(ctx, `SELECT tg_id FROM users WHERE role='admin' AND tg_id IS NOT NULL AND tg_id <> 0`)
	if err != nil {
		return nil
	}
	defer rows.Close()
	var out []int64
	for rows.Next() {
		var id int64
		if rows.Scan(&id) == nil {
			out = append(out, id)
		}
	}
	return out
}
