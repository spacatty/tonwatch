// Activity is the audit trail of people, not of names (that is `events`): sign-ups, sign-ins, AI
// runs, checkouts, and every change an admin makes to an account. The admin panel reads it for
// usage charts and per-account history.
const activitySchema = `
CREATE TABLE IF NOT EXISTS activity (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id  BIGINT NOT NULL,             -- whose account it is about
  actor_id BIGINT NOT NULL DEFAULT 0,   -- who did it when not the account itself (an admin)
  ts       BIGINT NOT NULL,
  kind     TEXT NOT NULL,               -- signup | login | logout | ai.<feature> | pay.checkout | pay.paid | admin.<what> …
  detail   TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS ix_activity_user ON activity(user_id, id DESC);
CREATE INDEX IF NOT EXISTS ix_activity_ts ON activity(ts);
CREATE INDEX IF NOT EXISTS ix_activity_kind ON activity(kind, id DESC);
`

type Activity struct {
	ID      int64  `json:"id"`
	UserID  int64  `json:"user_id"`
	ActorID int64  `json:"actor_id,omitempty"`
	TS      int64  `json:"ts"`
	Kind    string `json:"kind"`
	Detail  string `json:"detail,omitempty"`
	User    string `json:"user,omitempty"`  // feed: the account's label
	Actor   string `json:"actor,omitempty"` // feed: the admin's label
}

// Log writes one activity line. Failures are ignored: the trail must never break the action.
func (s *Store) Log(ctx context.Context, userID, actorID int64, kind, detail string) {
	if userID == 0 {
		return
	}
	s.DB.ExecContext(ctx, `INSERT INTO activity(user_id, actor_id, ts, kind, detail) VALUES(?,?,?,?,?)`, userID, actorID, now(), kind, detail)
}

// ActivityFilter narrows the feed: one account, one kind (a prefix like "ai." matches a family),
// and keyset paging by id.
type ActivityFilter struct {
	UserID int64
	Kind   string
	Before int64
	Limit  int
}

func (s *Store) Activity(ctx context.Context, f ActivityFilter) ([]Activity, error) {
	where, args := []string{"TRUE"}, []any{}
	if f.UserID > 0 {
		where, args = append(where, "a.user_id=?"), append(args, f.UserID)
	}
	if f.Kind != "" {
		if strings.HasSuffix(f.Kind, ".") {
			where, args = append(where, `a.kind LIKE ? ESCAPE '\'`), append(args, likeEsc(f.Kind)+"%")
		} else {
			where, args = append(where, "a.kind=?"), append(args, f.Kind)
		}
	}
	if f.Before > 0 {
		where, args = append(where, "a.id<?"), append(args, f.Before)
	}
	if f.Limit <= 0 || f.Limit > 500 {
		f.Limit = 100
	}
	label := func(t string) string {
		return `COALESCE(` + t + `.login, NULLIF('@' || ` + t + `.tg_username, '@'), NULLIF(` + t + `.tg_name, ''), ` + t + `.email, '')`
	}
	rows, err := s.DB.QueryContext(ctx, `SELECT a.id, a.user_id, a.actor_id, a.ts, a.kind, a.detail, `+label("u")+`, `+label("x")+`
		FROM activity a LEFT JOIN users u ON u.id = a.user_id LEFT JOIN users x ON x.id = a.actor_id AND a.actor_id > 0
		WHERE `+strings.Join(where, " AND ")+` ORDER BY a.id DESC LIMIT ?`, append(args, f.Limit)...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Activity{}
	for rows.Next() {
		var a Activity
		if err := rows.Scan(&a.ID, &a.UserID, &a.ActorID, &a.TS, &a.Kind, &a.Detail, &a.User, &a.Actor); err != nil {
			return nil, err
		}
		out = append(out, a)
	}
	return out, rows.Err()
}

// DayStat is one day of the admin charts (UTC days).
type DayStat struct {
	Day     string  `json:"day"` // 2006-01-02
	Signups int     `json:"signups"`
	Active  int     `json:"active"` // accounts with any activity that day
	Events  int     `json:"events"`
	Spent   int     `json:"spent"` // credits spent on AI features
	AICost  float64 `json:"ai_cost"`
	Paid    int     `json:"paid"` // payments completed
}

// Daily is the last `days` days, oldest first, with empty days filled in.
func (s *Store) Daily(ctx context.Context, days int) ([]DayStat, error) {
	start := time.Now().UTC().Truncate(24*time.Hour).AddDate(0, 0, -(days - 1))
	since := start.Unix()
	out := make([]DayStat, days)
	idx := map[string]int{}
	for i := range out {
		out[i].Day = start.AddDate(0, 0, i).Format("2006-01-02")
		idx[out[i].Day] = i
	}
	day := func(col string) string { return `to_char(to_timestamp(` + col + `) AT TIME ZONE 'UTC', 'YYYY-MM-DD')` }
	each := func(q string, set func(d *DayStat, n int, f float64)) error {
		rows, err := s.DB.QueryContext(ctx, q, since)
		if err != nil {
			return err
		}
		defer rows.Close()
		for rows.Next() {
			var d string
			var n int
			var f float64
			if err := rows.Scan(&d, &n, &f); err != nil {
				return err
			}
			if i, ok := idx[d]; ok {
				set(&out[i], n, f)
			}
		}
		return rows.Err()
	}
	queries := []struct {
		q   string
		set func(d *DayStat, n int, f float64)
	}{
		{`SELECT ` + day("created_at") + `, COUNT(*), 0 FROM users WHERE created_at >= ? GROUP BY 1`,
			func(d *DayStat, n int, _ float64) { d.Signups = n }},
		{`SELECT ` + day("ts") + `, COUNT(DISTINCT user_id), COUNT(*) FROM activity WHERE ts >= ? GROUP BY 1`,
			func(d *DayStat, n int, f float64) { d.Active, d.Events = n, int(f) }},
		{`SELECT ` + day("ts") + `, COALESCE(SUM(credits),0), COALESCE(SUM(cost),0) FROM ledger WHERE ts >= ? AND feature NOT IN ('topup','grant') GROUP BY 1`,
			func(d *DayStat, n int, f float64) { d.Spent, d.AICost = n, f }},
		{`SELECT ` + day("paid_at") + `, COUNT(*), 0 FROM payments WHERE status='paid' AND paid_at >= ? GROUP BY 1`,
			func(d *DayStat, n int, _ float64) { d.Paid = n }},
	}
	for _, q := range queries {
		if err := each(q.q, q.set); err != nil {
			return nil, err
		}
	}
	return out, nil
}

// FeatureUse is one AI feature's share of the spend since a moment.
type FeatureUse struct {
	Feature string  `json:"feature"`
	Runs    int     `json:"runs"`
	Credits int     `json:"credits"`
	Cost    float64 `json:"cost"`
	Users   int     `json:"users"`
}

func (s *Store) FeatureUsage(ctx context.Context, since int64) ([]FeatureUse, error) {
	rows, err := s.DB.QueryContext(ctx, `SELECT feature, COUNT(*), COALESCE(SUM(credits),0), COALESCE(SUM(cost),0), COUNT(DISTINCT user_id)
		FROM ledger WHERE ts >= ? AND feature NOT IN ('topup','grant') GROUP BY feature ORDER BY 3 DESC, 2 DESC`, since)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []FeatureUse{}
	for rows.Next() {
		var f FeatureUse
		if err := rows.Scan(&f.Feature, &f.Runs, &f.Credits, &f.Cost, &f.Users); err != nil {
			return nil, err
		}
		out = append(out, f)
	}
	return out, rows.Err()
}

// KindCount: how often each activity kind happened since a moment, most frequent first.
type KindCount struct {
	Kind string `json:"kind"`
	N    int    `json:"n"`
}

func (s *Store) ActivityKinds(ctx context.Context, since int64) ([]KindCount, error) {
	rows, err := s.DB.QueryContext(ctx, `SELECT kind, COUNT(*) FROM activity WHERE ts >= ? GROUP BY kind ORDER BY 2 DESC LIMIT 40`, since)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []KindCount{}
	for rows.Next() {
		var k KindCount
		if err := rows.Scan(&k.Kind, &k.N); err != nil {
			return nil, err
		}
		out = append(out, k)
	}
	return out, rows.Err()
}

// UserTotals are the headline counts of the admin overview.
type UserTotals struct {
	Total     int `json:"total"`
	Pro       int `json:"pro"`
	Admins    int `json:"admins"`
	Telegram  int `json:"telegram"`
	Active1d  int `json:"active_1d"`
	Active7d  int `json:"active_7d"`
	Active30d int `json:"active_30d"`
	New7d     int `json:"new_7d"`
	Credits   int `json:"credits"` // sitting on balances
}

func (s *Store) UserTotals(ctx context.Context) UserTotals {
	var t UserTotals
	ts := now()
	s.DB.QueryRowContext(ctx, `SELECT COUNT(*),
		COUNT(*) FILTER (WHERE plan='pro' OR plan_until > ?::bigint),
		COUNT(*) FILTER (WHERE role='admin'),
		COUNT(*) FILTER (WHERE tg_id IS NOT NULL),
		COUNT(*) FILTER (WHERE seen_at > ?::bigint),
		COUNT(*) FILTER (WHERE seen_at > ?::bigint),
		COUNT(*) FILTER (WHERE seen_at > ?::bigint),
		COUNT(*) FILTER (WHERE created_at > ?::bigint),
		COALESCE(SUM(credits),0)
		FROM users`, ts, ts-86400, ts-7*86400, ts-30*86400, ts-7*86400).
		Scan(&t.Total, &t.Pro, &t.Admins, &t.Telegram, &t.Active1d, &t.Active7d, &t.Active30d, &t.New7d, &t.Credits)
	return t
}

// UserFootprint is what one account has made, for the admin's account view.
type UserFootprint struct {
	Sessions  int     `json:"sessions"`
	Trackers  int     `json:"trackers"`
	Concepts  int     `json:"concepts"`
	Portfolio int     `json:"portfolio"`
	Starred   int     `json:"starred"`
	Hidden    int     `json:"hidden"`
	Spent     int     `json:"spent"`   // credits spent on AI, ever
	AICost    float64 `json:"ai_cost"` // what that cost us
	Bought    int     `json:"bought"`  // credits bought
	Granted   int     `json:"granted"` // credits given (or taken) by admins
}

func (s *Store) UserFootprint(ctx context.Context, id int64) UserFootprint {
	var f UserFootprint
	s.DB.QueryRowContext(ctx, `SELECT COUNT(*) FROM sessions WHERE user_id=? AND expires_at > ?`, id, now()).Scan(&f.Sessions)
	s.DB.QueryRowContext(ctx, `SELECT COUNT(*) FROM trackers WHERE user_id=?`, id).Scan(&f.Trackers)
	s.DB.QueryRowContext(ctx, `SELECT COUNT(*) FROM concepts WHERE user_id=?`, id).Scan(&f.Concepts)
	s.DB.QueryRowContext(ctx, `SELECT COUNT(*) FROM portfolio WHERE user_id=?`, id).Scan(&f.Portfolio)
	f.Starred, f.Hidden = s.UserNameCounts(ctx, id)
	s.DB.QueryRowContext(ctx, `SELECT
		COALESCE(SUM(credits) FILTER (WHERE feature NOT IN ('topup','grant')),0),
		COALESCE(SUM(cost) FILTER (WHERE feature NOT IN ('topup','grant')),0),
		COALESCE(SUM(credits) FILTER (WHERE feature='topup'),0),
		COALESCE(SUM(credits) FILTER (WHERE feature='grant'),0)
		FROM ledger WHERE user_id=?`, id).Scan(&f.Spent, &f.AICost, &f.Bought, &f.Granted)
	return f
}

// SetCredits puts the balance at exactly n and writes the difference to the ledger as a grant.
// Returns the difference.
func (s *Store) SetCredits(ctx context.Context, userID int64, n int, note string) (int, error) {
	tx, err := s.DB.BeginTx(ctx, nil)
	if err != nil {
		return 0, err
	}
	defer tx.Rollback()
	var cur int
	if err := tx.QueryRowContext(ctx, `SELECT credits FROM users WHERE id=? FOR UPDATE`, userID).Scan(&cur); err != nil {
		return 0, err
	}
	if n < 0 {
		n = 0
	}
	if d := n - cur; d != 0 {
		if err := addCreditsTx(ctx, tx, userID, d, LedgerEntry{Feature: "grant", Credits: d, Note: note}); err != nil {
			return 0, err
		}
	}
	return n - cur, tx.Commit()
}

// AddProDays extends bought Pro by days (negative shortens it; never below now).
func (s *Store) AddProDays(ctx context.Context, userID int64, days int) error {
	_, err := s.DB.ExecContext(ctx, `UPDATE users SET plan_until = CASE WHEN ?::int > 0 THEN GREATEST(plan_until, ?::bigint) + ?::bigint
		ELSE GREATEST(plan_until + ?::bigint, 0) END WHERE id=?`, days, now(), int64(days)*86400, int64(days)*86400, userID)
	return err
}
